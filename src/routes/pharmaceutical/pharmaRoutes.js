const { offlineSubmission } = require('../../middleware/sync/offlineSubmission');
const express = require('express');
const { protect } = require('../../middleware/auth/authMiddleware');
const controller = require('../../controllers/pharmaceutical/pharmaController');
const pharmaOrderRoutes = require('./pharmaOrderRoutes');
const riderController = require('../../controllers/pharmaceutical/pharmaRiderController');

const router = express.Router();
router.use(protect);
const waProfiles=require('../../controllers/whatsapp/whatsappProfileController');
router.get('/whatsapp-profiles',waProfiles.list);
router.post('/whatsapp-profiles',waProfiles.create);
router.patch('/whatsapp-profiles/:profileId',waProfiles.update);
router.post('/whatsapp-profiles/:profileId/default',waProfiles.makeDefault);
router.post('/whatsapp-profiles/:profileId/qr',waProfiles.qr);
router.post('/whatsapp-profiles/:profileId/disconnect',waProfiles.disconnect);
router.delete('/whatsapp-profiles/:profileId',waProfiles.remove);
const notifications = require('../../controllers/pharmaceutical/pharmaNotificationController');
router.get('/notifications', notifications.list);
router.patch('/notifications/:notificationId/read', notifications.read);
router.post('/riders', riderController.createRider);
router.get('/rider-dashboard', riderController.dashboard);
router.get('/branches', riderController.branches);
router.post('/branches', riderController.createBranch);
router.put('/branches/:branchId/riders', riderController.assignRiders);
router.put('/riders/:riderId/drop-sequence', riderController.reorderDrops);
router.patch('/dispatch/:orderId', riderController.dispatch);
router.put('/rider-profiles/:userId', riderController.saveProfile);
router.use('/orders', pharmaOrderRoutes);
router.get('/summary', controller.summary);
router.get('/visit-policies', controller.policies);
router.get('/doctors', controller.listDoctors);
router.post('/doctors', offlineSubmission('pharma-doctor', controller.createDoctor));
router.patch('/doctors/:doctorId', controller.updateDoctor);
router.get('/products', controller.listProducts);
router.get('/inventory', controller.listInventory);
router.get('/tour-plans', controller.listTourPlans);
router.post('/tour-plans', controller.createTourPlan);
router.patch('/tour-plans/:planId', controller.updateTourPlan);
router.get('/visits', controller.listVisits);
router.get('/visits/:visitId', controller.getVisit);
router.post('/visits', offlineSubmission('pharma-visit', controller.createVisit));

module.exports = router;
